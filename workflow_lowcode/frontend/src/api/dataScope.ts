/**
 * 数据范围（DataScope）的共享类型。
 *
 * 语义提醒（v3 可见集合白名单）：**关联即受控**——数据源一旦挂上权限对象就受数据权限控制；
 * **授权即赋予**——角色只有被授予某个权限对象才能看见它圈定的行，受控而未授权的角色一行都看不见；
 * 多个对象命中时取并集（对象间 OR、对象内 AND），空条件对象 = 全部行。
 * 数据权限就是查看权限：看不到则无法修改、删除（看即能操作，不再分读写轴）。
 * 授权（角色 × 权限对象）唯一入口是「角色管理 → 数据权限」，
 * 条件与关联的唯一入口是「数据权限 → 权限对象」，两端都没有面向数据源的接口。
 */

/** 授权主体类型：当前只有角色 */
export type DataScopeSubject = 'ROLE'

/** 权限对象里的单个条件（组内 AND） */
export interface DataScopeCondition {
  column: string
  op: string
  value?: unknown
}
